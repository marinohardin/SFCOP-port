# --- the readers, on invented bytes --------------------------------------------------------------

def _coff(symbols):
    """An i386 COFF object with no sections' contents: (name, value, section, storage) symbols."""
    strtab = b''
    recs = b''
    for name, value, section, storage in symbols:
        raw = name.encode()
        if len(raw) <= 8:
            field = raw.ljust(8, b'\0')
        else:
            field = b'\0\0\0\0' + struct.pack('<I', 4 + len(strtab))
            strtab += raw + b'\0'
        recs += field + struct.pack('<IhHBB', value, section, 0, storage, 0)
    head = struct.pack('<HHIIIHH', 0x14c, 0, 0, 20, len(symbols), 0, 0)
    return head + recs + struct.pack('<I', 4 + len(strtab)) + strtab


def test_coff_reader_tells_defined_from_undefined_externals():
    body = _coff([('_defined', 0, 1, 2), ('?long@name@@QAEXXZ', 0, 0, 2), ('_static', 0, 1, 3),
                  ('_common', 4, 0, 2), ('_weak', 0, 0, 105)])
    defined, undefined = gen_allowlist.coff_externals(body)
    assert defined == {'_defined', '_common'}
    assert undefined == {'?long@name@@QAEXXZ', '_weak'}


def test_coff_reader_ignores_anything_but_i386_objects():
    assert gen_allowlist.coff_externals(b'\x64\x86' + b'\0' * 30) == (set(), set())


def test_map_reader_takes_publics_and_their_library(tmp_path):
    m = tmp_path / 'x.map'
    m.write_text(
        ' Timestamp is 00000000\n'
        '  Address         Publics by Value              Rva+Base     Lib:Object\n'
        ' 0001:00000000       ?AllocNewScript@@YAPAVtScript@@XZ 10001000 f   Test.obj\n'
        ' 0001:00000010       _atexit                    10001010 f   LIBCMT:atonexit.obj\n'
        ' 0002:00000000       ??0tString@@QAE@PBD@Z      10002000 f i sfcTiger_MSVCR:tString.obj\n'
        ' Static symbols\n'
        ' 0001:00000020       _local                     10001020 f   Test.obj\n')
    assert gen_allowlist.map_publics(str(m)) == {
        '?AllocNewScript@@YAPAVtScript@@XZ': 'Test.obj',
        '_atexit': 'libcmt',
        '??0tString@@QAE@PBD@Z': 'sfctiger_msvcr',
    }


# --- against the install -------------------------------------------------------------------------

@pytest.mark.retail
@retail
def test_every_scripting_library_definition_is_on_the_allowlist():
    symbols = set(_symbols())
    missing = []
    for _, body in gen_allowlist.ar_members(LIB):
        for s in gen_allowlist.coff_externals(body)[0]:
            if gen_allowlist.bindable(s) and s not in symbols:
                missing.append(s)
    assert missing == []


@pytest.mark.retail
@retail
def test_allowlist_header_hash_is_the_installed_library():
    m = re.search(r'ScriptInterfaceR\.lib sha256 ([0-9a-f]{64})', ALLOWLIST.read_text(encoding='utf-8'))
    assert m.group(1) == gen_allowlist.verify_hash(LIB)


def test_allowlist_keeps_the_hand_added_name():
    """87 of the 88 shipped scripts import it and the generator does not produce it (the Lib set the
    template links lacks it), so a regeneration that drops it must fail here, not at the first
    translation."""
    lines = _lines()
    assert HAND_ADDED_NAME in lines
    at = lines.index(HAND_ADDED_NAME)
    assert lines[at - 1] == HAND_ADDED_NOTE
    assert f'# Added by hand (A3): {HAND_ADDED_NAME}' in '\n'.join(lines[:12])


def test_allowlist_keeps_the_hand_added_osspecific_names():
    """Every shipped script looks the game's compare-exchange up in its OSSpecific DLL at start-up and
    its lock throws without it; the generator does not produce these names, so a regeneration that
    drops them must fail here, not at the first run."""
    lines = _lines()
    header = '\n'.join(lines[:next(i for i, s in enumerate(lines) if not s.startswith('#'))])
    for name in OSSPECIFIC_NAMES:
        assert name in lines
    assert ('# Added by hand (I1b): OSSPECIFIC95.DLL!OS_InterlockedCompareExchange and\n'
            '#   OSSPECIFIC98.DLL!OS_InterlockedCompareExchange,') in header
