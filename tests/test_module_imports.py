"""The mission module import allow-list (DESIGN §6.4): src/app/scripts/allowlist.txt, its generator
tools/scr2native/gen_allowlist.py and the import check.

Most tests read only committed files. The tests marked with `retail` read the SDK in the install and
are skipped where it is absent.
"""
import os
import pathlib
import re
import struct
import subprocess
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / 'src' / 'app' / 'scripts'
ALLOWLIST = SCRIPTS / 'allowlist.txt'
FIXTURES = SCRIPTS / 'fixtures'
GEN = ROOT / 'tools' / 'scr2native' / 'gen_allowlist.py'
sys.path.insert(0, str(GEN.parent))
import gen_allowlist  # noqa: E402

LIB = os.path.join(gen_allowlist.sdk_dir(), 'Scripts', 'Libraries', 'ScriptInterfaceR.lib')
retail = pytest.mark.skipif(not os.path.isfile(LIB), reason='the SDK is not on this machine')


HAND_ADDED_NAME = 'KERNEL32.DLL!GetEnvironmentVariableA'
OSSPECIFIC_NAMES = ('OSSPECIFIC95.DLL!OS_InterlockedCompareExchange',
                    'OSSPECIFIC98.DLL!OS_InterlockedCompareExchange')
HAND_ADDED_NOTE = ('# Hand-added (A3) for the mission modules: their C runtime reads its heap-select '
                   'variable through it.')


def _lines():
    return ALLOWLIST.read_text(encoding='utf-8').splitlines()


def _symbols():
    return [s for s in _lines() if s and not s.startswith('#')]


def test_allowlist_is_sorted_by_byte_value_and_unique():
    symbols = _symbols()
    assert symbols == sorted(symbols, key=lambda s: s.encode('latin1'))
    assert len(symbols) == len(set(symbols))


def test_allowlist_header_names_the_generator_and_the_sdk():
    lines = _lines()
    header = lines[:next(i for i, s in enumerate(lines) if not s.startswith('#'))]
    text = '\n'.join(header)
    assert 'Generated by tools/scr2native/gen_allowlist.py; do not edit.' in text
    assert 'the SDK, release R2.1,' in text
    assert re.search(r'^# References the template link left unresolved, dropped: \d+\.$', text, re.M)
    assert re.search(r'ScriptInterfaceR\.lib sha256 [0-9a-f]{64}', text)
    # The header comes first; the only comment line among the symbols is the note above the A3
    # hand-added name (test_allowlist_keeps_the_hand_added_name).
    assert [s for s in lines[len(header):] if s.startswith('#')] == [HAND_ADDED_NOTE]


def test_allowlist_header_counts_match_its_symbols():
    m = re.search(r'^# Symbols: (\d+)\.', ALLOWLIST.read_text(encoding='utf-8'), re.M)
    assert m and int(m.group(1)) == len(_symbols())


def test_allowlist_holds_each_part():
    symbols = set(_symbols())
    # library: ScriptInterfaceR.lib's own definitions
    assert '??0tShipInfo@@QAE@XZ' in symbols
    assert '_ScriptEntry' in symbols and '_MissionSpecEntry' in symbols
    # linked: sfcTiger's tString and the dmp3D stand-in's tMatrix::mIdentity
    assert '??0tString@@QAE@PBD@Z' in symbols
    assert '?mIdentity@tMatrix@@QAEXXZ' in symbols
    # runtime and imports
    assert '_atexit' in symbols
    assert 'KERNEL32.DLL!HeapAlloc' in symbols


def test_allowlist_leaves_out_compiler_generated_names():
    for s in _symbols():
        assert not gen_allowlist._NOT_BINDABLE.match(s), s


def test_scripting_library_version_agrees_with_the_loader_header():
    header = (SCRIPTS / 'ModuleLoader.h').read_text(encoding='utf-8')
    m = re.search(r'kScriptVersion = ([0-9.]+)f;', header)
    assert m, 'ModuleLoader.h declares kScriptVersion'
    assert f'scripting library version {m.group(1)},' in ALLOWLIST.read_text(encoding='utf-8')


def test_conforming_fixture_passes_the_check():
    imports = gen_allowlist.read_symbols(FIXTURES / 'conforming.imports')
    assert len(imports) == 10
    assert gen_allowlist.foreign_imports(imports, _symbols()) == []


