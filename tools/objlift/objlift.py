#!/usr/bin/env python3
"""Lift the VC6 COFF objects of decompiled units into the native build's guest (DESIGN §6.3, §7.2).

    objlift.py --obj [UNIT=]UNIT.obj ... --manifest game/manifest.tsv --symbols ghidra/exports
               --out DIR [--exe StarFleetOP.exe] [--lifted LIFT/out/gen] [--pcrecomp DIR]
               [--check] [--no-lift]

Each claimed function (a `vc6` row of the manifest) is placed at its original address, every other
live section at its original address when the exe holds it, else in the reserved guest range;
the relocations are resolved against the objects and the exe's symbols; and the placed code is
lifted with pcrecomp the way cmake/lifter/run_lift.py lifts the exe (placement.py, liftcode.py).

Writes into --out, each file only when its content changed:

    objlift_code.c       the lifted bodies, named as the exe lift names them (sub_006FC5A0)
    objlift_funcs.h      their declarations
    objlift_table.c      the override table (src/app/guest/override.h) and the data image
    objlift_dispatch.c   the exe lift's dispatch table with the fresh bodies merged in (--lifted)
    objlift_weak.h       `#pragma weak` for each exe-lift body the objects replace, force-included
                         into the exe lift's files so their bodies give way
    objlift_report.txt   where every section went, every relocation, every judgement call

--check writes nothing and exits 1 when a file in --out is not what this run would write.
--no-lift places and reports only (no pcrecomp needed). --obj names the unit (`Common/X.cpp=`)
when two objects share a file name (split at the first `=`, so the path may contain one but then
needs the `UNIT=` before it); otherwise the object's stem matches the manifest's source.
The object's /FAs listing (UNIT.asm beside it, as the harness writes it) says which compiled
symbol each annotation claims; without one, the mangled name in functions.csv is used.

Exit status: 0 done, 1 --check found a difference, 2 an input the lift cannot honour (the message
names the symbol or section).
"""
import argparse
import csv
import hashlib
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
for _p in (HERE, REPO):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import liftcode  # noqa: E402
import placement  # noqa: E402
from placement import PlacementError  # noqa: E402

MODULE = 'STARFLEETOP'
OUTPUTS = ('objlift_code.c', 'objlift_funcs.h', 'objlift_table.c', 'objlift_dispatch.c',
           'objlift_weak.h', 'objlift_report.txt')
HEADER = '/* Generated by tools/objlift/objlift.py from the VC6 objects of the claimed units. */\n'


# --- inputs ------------------------------------------------------------------------------------

def read_manifest(path):
    """[(address, size, symbol, source)] of the functions the manifest claims for VC6."""
    rows = []
    with open(path, newline='') as f:
        for r in csv.DictReader(f, delimiter='\t'):
            if 'vc6' not in r['modes'].split():
                continue
            rows.append((int(r['address'], 16), int(r['size'] or 0), r['symbol'], r['source']))
    return rows


def parse_obj_args(specs):
    """--obj [UNIT=]PATH -> [(unit or None, path)]"""
    out = []
    for s in specs:
        unit, sep, path = s.partition('=')   # the first '=' splits; a path with '=' needs a UNIT= before it
        if not sep:
            unit, path = None, s
        if not os.path.isfile(path):
            raise PlacementError(f'no object at {path}')
        out.append((unit or None, path))
    return out


def object_for_unit(source, objs):
    explicit = [p for u, p in objs if u == source]
    if explicit:
        return explicit[0]
    stem = os.path.splitext(os.path.basename(source))[0].lower()
    hits = [p for u, p in objs if u is None
            and os.path.splitext(os.path.basename(p))[0].lower() == stem]
    if len(hits) > 1:
        raise PlacementError(f'{source}: {len(hits)} objects are named {stem}.obj; name the unit '
                             f'with --obj {source}=PATH')
    return hits[0] if hits else None


def claimed_symbol(address, source, obj_path, game, fallback):
    """The compiled symbol the annotation for `address` claims: from the object's /FAs listing,
    with the harness's own rule (harness/lib/source.py), else the mangled name in functions.csv."""
    from harness.lib import source as hsource
    listing = os.path.splitext(obj_path)[0] + '.asm'
    unit = os.path.join(game, source)
    if os.path.isfile(listing) and os.path.isfile(unit):
        anns = hsource.scan_annotations(os.path.dirname(unit), MODULE)
        mine = [a for a in anns.get(address, []) if a.kind == 'FUNCTION'
                and os.path.samefile(a.path, unit)]
        if len(mine) == 1:
            others = [a.line for lst in anns.values() for a in lst
                      if os.path.samefile(a.path, unit) and a.line != mine[0].line]
            sym = hsource.symbol_for_annotation(open(listing, encoding='latin1').read(), unit,
                                                mine[0].line, others)
            if isinstance(sym, str):
                return sym
            if isinstance(sym, list) and fallback in sym:
                return fallback
    if fallback:
        return fallback
    raise PlacementError(f'0x{address:08x} ({source}): no listing says which compiled symbol its '
                         'annotation claims, and functions.csv has no mangled name for it')


def check_exe(path):
    """A PeImage of the exe after checking its hash against analysis/results/retail_hashes.sha256."""
    from harness.lib import coff, paths
    raw = open(path, 'rb').read()
    got = hashlib.sha256(raw).hexdigest()
    want = None
    with open(paths.HASHES) as f:
        for line in f:
            h, p = line.rstrip('\n').split('  ', 1)
            if p == paths.EXE_REL:
                want = h
    if got != want:
        raise PlacementError(f'{path} has sha256 {got}, not the original exe\'s {want}')
    return coff.PeImage(raw)


def read_lifted_names(gen):
    """Every body the exe lift defines (its recomp_funcs.h), as addresses."""
    out = set()
    with open(os.path.join(gen, 'recomp_funcs.h')) as f:
        for line in f:
            if line.startswith('void sub_') and line.rstrip().endswith('(void);'):
                out.add(int(line[9:17], 16))
    return out


def read_dispatch(gen):
    """The exe lift's dispatch table: ([(va, name)], entry va)."""
    entries, entry_va = [], None
    with open(os.path.join(gen, 'recomp_dispatch.c')) as f:
        for line in f:
            s = line.strip()
            if s.startswith('{ 0x') and s.endswith('},'):
                va, name = s[2:-2].split(',')
                entries.append((int(va.strip().rstrip('u'), 16), name.strip()))
            elif s.startswith('const uint32_t sfcop_entry_va = '):
                entry_va = int(s.split('=')[1].strip().rstrip(';').rstrip('u'), 16)
    if entry_va is None:
        raise PlacementError(f'{gen}/recomp_dispatch.c has no sfcop_entry_va line')
    return entries, entry_va


# --- the run -----------------------------------------------------------------------------------

class Run:
    def __init__(self, args):
        self.args = args
        self.started = time.time()
        self.functions_csv = args.symbols if args.symbols.endswith('.csv') \
            else os.path.join(args.symbols, 'functions.csv')
        from harness.lib import paths
        tsvs = args.sdk_symbols if args.sdk_symbols is not None else paths.SYMBOL_TSVS
        self.index = placement.SymbolIndex.from_harness(self.functions_csv, tsvs)
        self.exe = check_exe(args.exe) if args.exe else None
        self.objs = parse_obj_args(args.obj)
        self.lifted = read_lifted_names(args.lifted) if args.lifted else None

    def claims(self):
        out, used = [], set()
        by_addr = self.index.harness_index.by_address
        for address, size, name, source in read_manifest(self.args.manifest):
            obj = object_for_unit(source, self.objs)
            if obj is None:
                raise PlacementError(f'0x{address:08x} {name}: no --obj for its unit {source}')
            used.add(obj)
            fn = by_addr.get(address)
            sym = claimed_symbol(address, source, obj, self.args.game, fn.mangled if fn else '')
            out.append(placement.Claim(address, size, sym, name, source))
        return sorted(out, key=lambda c: c.address)

    def place(self):
        claims = self.claims()
        objects = [placement.InputObject(p, u) for u, p in self.objs]
        placement._claimed_sections(objects, claims)
        evidence, notes = {}, []
        if self.exe is not None:
            evidence, notes = placement.exact_function_evidence(claims, objects, self.exe,
                                                                self.index.harness_index)
        exe_sections = None
        if self.exe is not None:
            exe_sections = [(self.exe.image_base + va, self.exe.image_base + va + max(vs, rs))
                            for _, va, vs, _, rs in self.exe.sections]
        placer = placement.Placer(objects, claims, self.index, evidence, exe_sections)
        result = placer.place()
        result.notes[:0] = notes
        return claims, result

    def read(self, result):
        """read(va, n) over the placed sections, then the exe."""
        spans = [(s.va, s.va + len(img), img) for s, img in result.images.items()]

        def read(va, n):
            for lo, hi, img in spans:
                if lo <= va and va + n <= hi:
                    return img[va - lo:va - lo + n]
            if self.exe is not None:
                try:
                    return self.exe.read(va, n)
                except Exception:  # noqa: BLE001 -- outside the image, as run_lift.py's read
                    return None
            return None
        return read


def entries_by_section(result, claims):
    """Each placed code section's entries: its function symbols, and the addresses in it that a
    data section's relocation names (catch blocks and funclets the EH tables point at)."""
    out = {s: set() for s in result.code_sections()}
    for sec in out:
        for sym in sec.symbols:
            if sym.is_function:
                out[sec].add((sec.va + sym.value) & 0xFFFFFFFF)
        if not out[sec]:
            out[sec].add(sec.va)
    data_labels = {s.label for s in result.sections if not s.is_code}
    for label, _off, _typ, _sym, addr, _how in result.relocations:
        if label not in data_labels:
            continue
        for sec in out:
            if sec.va <= addr < sec.va + len(sec.data):
                out[sec].add(addr)
    for c in claims:
        for sec in out:
            if sec.va <= c.address < sec.va + len(sec.data):
                out[sec].add(c.address)
    return {s: sorted(v) for s, v in out.items()}


def emit(run, claims, result, bodies):
    """{file name: text}"""
    files = {}
    claimed = {c.address: i for i, c in enumerate(claims)}
    fresh = result.fresh_sections()
    image = bool(fresh)
    names = sorted({(b.va, b.name) for b in bodies})

    funcs = [HEADER, '#pragma once\n#include <stdint.h>\n\n',
             'void sfcop_guest_entered(unsigned index);\n',
             'void sfcop_guest_load_objects(void);\n',
             'extern int sfcop_guest_objects_loaded;\n\n']
    funcs += ['void %s(void);\n' % n for _, n in names]
    files['objlift_funcs.h'] = ''.join(funcs)

    code = [HEADER, '#define RECOMP_GENERATED_CODE\n#include "recomp_types.h"\n',
            '#include "recomp_funcs.h"\n#include "objlift_funcs.h"\n',
            '#include <math.h>\n#include <string.h>\n\n']
    for b in bodies:
        sources = sorted({c.source for c in b.section.claims}) or [b.section.obj.unit or
                                                                   os.path.basename(b.section.obj.path)]
        code.append(f'/* 0x{b.va:08X} {b.section.mode} {b.section.name}, game/{", ".join(sources)} */\n')
        code.append(b.c.rstrip('\n') + '\n\n')
    files['objlift_code.c'] = ''.join(code)

    table = [HEADER, '#include "recomp_types.h"\n#include "win32hle.h"\n',
             '#include "objlift_funcs.h"\n\n#define SFCOP_GUEST_OBJECTS_IMPLEMENTATION\n',
             '#include "app/guest/override.h"\n\n']
    if claims:
        table.append('const sfcop_guest_override sfcop_guest_overrides[] = {\n')
        for c in claims:
            table.append('    {0x%08Xu, sub_%08X, "%s", "%s"},\n' % (c.address, c.address,
                                                                    _cstr(c.name), _cstr(c.source)))
        table.append('};\n')
    else:
        table.append('const sfcop_guest_override sfcop_guest_overrides[] = {{0u, 0, 0, 0}};\n')
    table.append('const unsigned sfcop_guest_override_count = %du;\n' % len(claims))
    table.append('uint32_t sfcop_guest_calls[%d];\n\n' % max(1, len(claims)))
    table.append('/* The data image: fresh sections in the reserved guest range 0x%08X-0x%08X. */\n'
                 % (placement.RESERVED_BASE, placement.RESERVED_BASE + placement.RESERVED_SIZE))
    rows = []
    for i, sec in enumerate(fresh):
        img = result.images[sec]
        if sec.is_bss:
            rows.append('    {0x%08Xu, %du, 0}, /* %s */\n' % (sec.va, len(img), _cstr(sec.label)))
            continue
        table.append('static const uint8_t sfcop_guest_object_bytes_%d[%d] = {' % (i, len(img)))
        for j in range(0, len(img), 16):
            table.append('\n    ' + ', '.join('0x%02x' % x for x in img[j:j + 16]) + ',')
        table.append('\n};\n')
        rows.append('    {0x%08Xu, %du, sfcop_guest_object_bytes_%d}, /* %s */\n'
                    % (sec.va, len(img), i, _cstr(sec.label)))
    table.append('const sfcop_guest_object_section sfcop_guest_object_sections[] = {\n')
    table += rows or ['    {0u, 0u, 0},\n']
    table.append('};\nconst unsigned sfcop_guest_object_section_count = %du;\n' % len(rows))
    size = result.reserved_end - placement.RESERVED_BASE
    table.append('const uint32_t sfcop_guest_object_base = 0x%08Xu;\n' % placement.RESERVED_BASE)
    table.append('const uint32_t sfcop_guest_object_size = 0x%Xu;\n' % ((size + 0xFFFF) & ~0xFFFF))
    files['objlift_table.c'] = ''.join(table)

    exe_names = run.lifted
    weak = [HEADER, '/* The exe lift\'s bodies that the lifted objects replace. */\n']
    for va, n in names:
        in_exe = (va in exe_names) if exe_names is not None else (va in claimed)
        if in_exe:
            weak.append('#pragma weak %s\n' % n)
    files['objlift_weak.h'] = ''.join(weak)

    if run.args.lifted:
        entries, entry_va = read_dispatch(run.args.lifted)
        have = {va for va, _ in entries}
        merged = sorted(entries + [(va, n) for va, n in names if va not in have])
        disp = [HEADER, '/* The exe lift\'s recomp_dispatch.c, with the lifted objects\' fresh '
                'bodies merged in. */\n#include "recomp_types.h"\n#include "recomp_funcs.h"\n'
                '#include "objlift_funcs.h"\n\nconst recomp_dispatch_entry_t recomp_dispatch_table[] = {\n']
        disp += ['    { 0x%08Xu, %s },\n' % (va, n) for va, n in merged]
        disp.append('};\nconst uint32_t recomp_dispatch_count = %d;\n'
                    'const uint32_t sfcop_entry_va = 0x%08Xu;\n' % (len(merged), entry_va))
        files['objlift_dispatch.c'] = ''.join(disp)
    else:
        files['objlift_dispatch.c'] = HEADER + '/* No exe lift was given (--lifted): nothing to merge. */\n'

    files['objlift_report.txt'] = report(run, claims, result, bodies, image)
    return files


def _cstr(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def compare_with_exe(run, claims, result):
    """One line per claimed function: are its placed bytes the exe's?"""
    if run.exe is None:
        return []
    lines = []
    for c in claims:
        sec = next(s for s in result.sections if c in s.claims)
        sym = next(s for s in sec.symbols if s.name == c.symbol)
        img = result.images[sec]
        later = [s.value for s in sec.symbols if s.is_function and s.value > sym.value]
        end = min(later) if later else len(img)
        mine = img[sym.value:end].rstrip(b'\x90\xcc')
        theirs = run.exe.read(c.address, len(mine))
        diff = next((i for i in range(len(mine)) if mine[i] != theirs[i]), None)
        what = 'identical to the exe' if diff is None else f'differs from the exe at +0x{diff:x}'
        lines.append(f'0x{c.address:08x} {c.symbol}: {len(mine)} bytes placed, {what}')
    return lines


def report(run, claims, result, bodies, image):
    out = ['objlift report', '',
           f'reserved guest range 0x{placement.RESERVED_BASE:08x}-'
           f'0x{placement.RESERVED_BASE + placement.RESERVED_SIZE:08x}, used '
           f'0x{result.reserved_end - placement.RESERVED_BASE:x} bytes', '', 'claimed functions:']
    out += [f'  0x{c.address:08x} {c.symbol} ({c.name}, game/{c.source})' for c in claims]
    cmp = compare_with_exe(run, claims, result)
    if cmp:
        out += ['', 'placed bytes against the exe:'] + ['  ' + x for x in cmp]
    out += ['', 'sections:']
    for s in result.sections:
        where = 'apart     ' if s.va is None else f'0x{s.va:08x}'
        out.append(f'  {s.label:<44} {s.mode:<8} {where} {len(s.data):>6} bytes  {s.evidence}')
    out += ['', 'dropped:'] + [f'  {lbl:<44} {why}' for lbl, why in result.dropped]
    out += ['', 'relocations:']
    for label, off, typ, sym, addr, how in result.relocations:
        out.append(f'  {label}+0x{off:x} {typ:<7} {sym} -> 0x{addr:08x} ({how})')
    out += ['', 'lifted bodies:'] + [f'  {b.name} {b.section.mode}' for b in bodies]
    out += ['', 'data image: ' + (f'{len(result.fresh_sections())} section(s)' if image else 'empty')]
    if result.notes:
        out += ['', 'notes:'] + ['  ' + n for n in result.notes]
    return '\n'.join(out) + '\n'


def write_or_check(out_dir, files, check):
    """Write each file only when its content changed; with check, write nothing and list what
    differs. Returns the names that differ."""
    differ = []
    if not check:
        os.makedirs(out_dir, exist_ok=True)
    for name in OUTPUTS:
        text = files.get(name)
        if text is None:
            continue
        path = os.path.join(out_dir, name)
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old == text:
            continue
        differ.append(name)
        if not check:
            with open(path + '.tmp', 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            os.replace(path + '.tmp', path)
    return differ


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--obj', action='append', required=True, metavar='[UNIT=]PATH')
    ap.add_argument('--manifest', required=True)
    ap.add_argument('--symbols', required=True, help='ghidra/exports, or its functions.csv')
    ap.add_argument('--sdk-symbols', action='append', metavar='TSV',
                    help='more name evidence (default: the harness\'s SDK match tables)')
    ap.add_argument('--game', default=os.path.join(REPO, 'game'))
    ap.add_argument('--exe', help='the original exe: evidence from exact functions, SECTION/SECREL')
    ap.add_argument('--lifted', metavar='GEN', help='the exe lift\'s out/gen directory')
    ap.add_argument('--pcrecomp', default=os.environ.get('SFCOP_PCRECOMP_DIR', ''))
    ap.add_argument('--out', required=True)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--no-lift', action='store_true')
    a = ap.parse_args(argv)
    try:
        run = Run(a)
        claims, result = run.place()
        bodies = []
        if not a.no_lift:
            if not a.pcrecomp:
                raise PlacementError('no pcrecomp clone: give --pcrecomp or set SFCOP_PCRECOMP_DIR')
            pcr = liftcode.load_pcrecomp(os.path.join(a.pcrecomp, 'tools'))
            claimed = {c.address: i for i, c in enumerate(claims)}
            load = 'SFCOP_GUEST_OBJECTS_LOAD(); ' if result.fresh_sections() else ''

            def hook(va):
                h = load
                if va in claimed:
                    h += 'sfcop_guest_entered(%du); ' % claimed[va]
                return h.strip()

            lifted = None
            if run.lifted is not None:
                ours = {a_ for s, e in entries_by_section(result, claims).items() for a_ in e}
                lifted = run.lifted | ours
            iat = {next(iter(v)): ('', k[len('__imp__'):]) for k, v in run.index.known.items()
                   if k.startswith('__imp__') and len(v) == 1}
            bodies = liftcode.lift_sections(pcr, result.code_sections(), result.images,
                                            entries_by_section(result, claims), run.read(result),
                                            lifted, iat, hook)
        files = emit(run, claims, result, bodies)
        if a.no_lift:
            files = {'objlift_report.txt': files['objlift_report.txt']}
    except (PlacementError, liftcode.LiftError) as e:
        print(f'objlift: {e}', file=sys.stderr)
        return 2
    differ = write_or_check(a.out, files, a.check)
    secs = time.time() - run.started
    if a.check:
        for n in differ:
            print(f'objlift: {os.path.join(a.out, n)} is out of date', file=sys.stderr)
        return 1 if differ else 0
    print(f'objlift: {len(claims)} claimed, {len(bodies)} bodies lifted, '
          f'{len(result.fresh_sections())} fresh section(s), {len(differ)} file(s) changed, '
          f'{secs:.1f} s')
    return 0


if __name__ == '__main__':
    sys.exit(main())
